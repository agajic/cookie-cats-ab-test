  /* ============================================================
     5. THE FOCAL MOMENT — a thousand resampled worlds
     ============================================================ */
  var bootstrapState = { drawn: false, dots: null, timer: null };

  function chartBootstrap(mount, animate) {
    var g = svgFor(mount), s = g.s, w = g.w, h = g.h;
    var b = D.bootstrap;
    var padL = 22, padR = 22, padT = 34, padB = 48;
    var lo = Math.min(-0.12, b.edges[0]), hi = b.edges[b.edges.length - 1];
    var X = function (v) { return padL + (w - padL - padR) * (v - lo) / (hi - lo); };

    // bin the raw values so every resample is one mark
    var nb = b.bins.length, e0 = b.edges[0], e1 = b.edges[nb];
    var counts = new Array(nb).fill(0);
    var placed = b.values.map(function (v) {
      var idx = Math.min(nb - 1, Math.max(0, Math.floor((v - e0) / (e1 - e0) * nb)));
      var stack = counts[idx]++;
      return { v: v, bin: idx, stack: stack };
    });
    var maxStack = Math.max.apply(null, counts);
    var binW = (X(e1) - X(e0)) / nb;
    var avail = h - padT - padB;
    var dotStep = Math.min(4.2, avail / maxStack);
    var dotR = Math.max(1.1, Math.min(1.9, dotStep * 0.42));
    var base = h - padB;

    // 95% interval band
    el('rect', {
      x: X(b.ci_lo), y: padT - 6, width: X(b.ci_hi) - X(b.ci_lo), height: base - padT + 6,
      fill: css('--d-cobalt'), opacity: .10
    }, s);

    // axis
    el('line', { x1: padL, y1: base, x2: w - padR, y2: base, class: 'axis-firm' }, s);
    var tickVals = [0, 0.4, 0.8, 1.2, 1.6];
    tickVals.forEach(function (v) {
      if (v < lo || v > hi) return;
      el('line', { x1: X(v), y1: base, x2: X(v), y2: base + 5, class: 'axis' }, s);
      txt(s, X(v), base + 19, (v > 0 ? '+' : '') + v.toFixed(1), 'tick', 'middle');
    });
    txt(s, (padL + w - padR) / 2, h - 8, 'gate 30 minus gate 40  (percentage points)', 'tick', 'middle');

    // the zero line — nothing crosses it
    el('line', { x1: X(0), y1: padT - 22, x2: X(0), y2: base + 8, stroke: css('--rust'), 'stroke-width': 2 }, s);
    var zt = txt(s, X(0) - 8, padT - 12, 'no difference', 'tick tick-strong', 'end');
    zt.setAttribute('fill', css('--rust'));

    // the marks
    var layer = el('g', {}, s);
    var nodes = placed.map(function (p) {
      var cx = X(e0) + (p.bin + 0.5) * binW;
      var cy = base - 3 - p.stack * dotStep - dotR;
      var c = el('circle', { cx: cx, cy: cy, r: dotR, fill: css('--d-cobalt') }, layer);
      if (animate && !REDUCED) c.setAttribute('opacity', '0');
      return c;
    });

    // CI caption
    var ci = txt(s, X(b.ci_hi) + 8, padT + 6,
      '95% of worlds: +' + b.ci_lo.toFixed(2) + ' to +' + b.ci_hi.toFixed(2) + ' pp', 'tick', 'start');
    ci.setAttribute('fill', css('--d-ink-2'));
    if (X(b.ci_hi) + 190 > w) { ci.setAttribute('text-anchor', 'end'); ci.setAttribute('x', w - padR); ci.setAttribute('y', padT - 12); }

    bootstrapState.dots = nodes;
    return s;
  }

  function runBootstrapAnimation() {
    var nodes = bootstrapState.dots;
    if (!nodes || REDUCED) return;
    var i = 0, total = nodes.length, start = null, DUR = 1700;
    function frame(ts) {
      if (start === null) start = ts;
      var t = Math.min(1, (ts - start) / DUR);
      var eased = 1 - Math.pow(1 - t, 3);
      var target = Math.floor(eased * total);
      while (i < target) { nodes[i].setAttribute('opacity', '1'); i++; }
      if (t < 1) requestAnimationFrame(frame);
      else for (; i < total; i++) nodes[i].setAttribute('opacity', '1');
    }
    requestAnimationFrame(frame);
  }

