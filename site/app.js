  /* ---------- tiny svg helpers ---------- */
  function el(name, attrs, parent) {
    var e = document.createElementNS(NS, name);
    if (attrs) for (var k in attrs) e.setAttribute(k, attrs[k]);
    if (parent) parent.appendChild(e);
    return e;
  }
  function txt(parent, x, y, s, cls, anchor) {
    var t = el('text', { x: x, y: y, class: cls || 'tick' }, parent);
    if (anchor) t.setAttribute('text-anchor', anchor);
    t.textContent = s;
    return t;
  }
  function svgFor(mount) {
    mount.innerHTML = '';
    var w = Math.max(240, mount.clientWidth);
    var h = Math.max(140, mount.clientHeight);
    var s = el('svg', { viewBox: '0 0 ' + w + ' ' + h, width: w, height: h }, mount);
    s.style.fontFamily = 'inherit';
    return { s: s, w: w, h: h };
  }
  function lerp(a, b, t) { return a + (b - a) * t; }
  function css(v) { return getComputedStyle(document.documentElement).getPropertyValue(v).trim(); }

  /* ============================================================
     1. The gate — two lanes, one wall each
     ============================================================ */
  function chartGate(mount) {
    var g = svgFor(mount), s = g.s, w = g.w, h = g.h;
    var padL = 14, padR = 14, maxLvl = 52;
    var x = function (lvl) { return padL + (w - padL - padR) * (lvl / maxLvl); };
    var lanes = [
      { name: 'Gate 30', sub: 'control', gate: 30, color: css('--cobalt') },
      { name: 'Gate 40', sub: 'variant', gate: 40, color: css('--rust') }
    ];
    // the gap must clear lane 1's tick labels before lane 2's name
    var laneH = 46, top = 34, gap = 64;

    lanes.forEach(function (ln, i) {
      var y = top + i * (laneH + gap);
      txt(s, padL, y - 10, ln.name.toUpperCase() + '  ·  ' + ln.sub, 'tick tick-strong');

      // free-play run
      el('rect', {
        x: x(0), y: y, width: x(ln.gate) - x(0), height: laneH,
        fill: ln.color, opacity: 0.10
      }, s);
      // the track
      el('line', { x1: x(0), y1: y + laneH, x2: x(maxLvl), y2: y + laneH, class: 'axis-firm' }, s);
      // level ticks
      [10, 20, 30, 40, 50].forEach(function (lv) {
        el('line', { x1: x(lv), y1: y + laneH, x2: x(lv), y2: y + laneH + 5, class: 'axis' }, s);
        txt(s, x(lv), y + laneH + 18, lv, 'tick', 'middle');
      });
      // the wall
      var gx = x(ln.gate);
      el('rect', { x: gx - 3, y: y - 4, width: 6, height: laneH + 8, fill: ln.color }, s);
      for (var k = 0; k < 5; k++) {
        el('line', {
          x1: gx + 4, y1: y - 2 + k * (laneH + 4) / 5,
          x2: gx + 12, y2: y - 2 + k * (laneH + 4) / 5,
          stroke: ln.color, 'stroke-width': 1.5, opacity: .5
        }, s);
      }
      txt(s, x(ln.gate / 2), y + laneH / 2 + 5, 'free play', 'tick', 'middle');
    });
    return s;
  }

